#!/usr/bin/env python3
"""Export reviewed tug registration/stack metadata to shared Java; no image edits."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read(name):
    with (ROOT / 'docs/art-studies' / name).open() as source:
        rows = list(csv.DictReader(source))
    assert [int(row['frame']) for row in rows] == list(range(32))
    return rows


registration = read('tug-isometric-v5-registration.csv')
stacks = read('tug-isometric-v5-stack-anchors.csv')
assert len({row['uniform_scale'] for row in registration}) == 1
assert all(row['id'] == 'stack.main' for row in stacks)
arrays = []
for name, rows, key in [('PX', registration, 'pivot_x'),
                        ('PY', registration, 'pivot_y'),
                        ('STACK_X', stacks, 'source_x'),
                        ('STACK_Y', stacks, 'source_y')]:
    values = [float(row[key]) for row in rows]
    assert all(0 < value < 1 for value in values)
    arrays.append('    private static final float[] ' + name + '={' +
                  ','.join(f'{value:.8f}f' for value in values) + '};')
text = '''package com.bargeboss.game;

/** Approved v5 source-cell metadata. Generated by tools/export-tug-runtime.py.
 *  Stack outlets are visually calibrated; frame 10 remains occluded/estimated.
 *  Full guide light/fender inventory is retained in the art-study JSON, pending
 *  pixel review before those points are enabled for runtime effects. */
public final class TugArt {
    public static final float HULL_FRACTION=.78f, SCALE=.8957603f;
    private TugArt() {}
''' + '\n'.join(arrays) + '''
    public static float pivotX(int frame) { return PX[frame]; }
    public static float pivotY(int frame) { return PY[frame]; }
    public static float stackX(int frame) { return STACK_X[frame]; }
    public static float stackY(int frame) { return STACK_Y[frame]; }
    public static boolean stackReviewed(int frame) { return frame!=10; }
}
'''
(ROOT / 'core/com/bargeboss/game/TugArt.java').write_text(text)
print('Exported 32 registered views and stack.main anchors to TugArt.java')
