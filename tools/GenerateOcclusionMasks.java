package com.bargeboss.game;

import java.awt.image.BufferedImage;
import java.io.*;
import java.nio.charset.StandardCharsets;
import java.util.*;
import javax.imageio.ImageIO;

/** Derive conservative opaque interiors from production PNGs; never modifies artwork. */
public final class GenerateOcclusionMasks {
    public static void main(String[] args)throws Exception {
        boolean check=args.length>0 && args[0].equals("--check");
        File output=check?File.createTempFile("bargeboss-masks-", ".java"):new File(args[0]);
        int[] atlases={0,1,2,3,4,10,16,17,18,19};
        Map<String,BufferedImage> images=new HashMap<>();
        try(PrintWriter out=new PrintWriter(new OutputStreamWriter(new FileOutputStream(output),StandardCharsets.UTF_8))) {
            out.println("package com.bargeboss.game;\n\n/** Generated by tools/GenerateOcclusionMasks.java. 64x64 opaque-interior masks. */\nfinal class OcclusionMasks {");
            out.println("    static long[][] rows(int atlas) { switch(atlas) {");
            for(int atlas:atlases)out.println("        case "+atlas+": return Atlas"+atlas+".ROWS;");
            out.println("        default: throw new IllegalArgumentException(\"No occlusion mask for atlas \"+atlas);\n    }}");
            out.println("    private static long[][] decode(String[] frames) { long[][] rows=new long[frames.length][64]; for(int f=0;f<frames.length;f++) for(int y=0;y<64;y++) {long bits=0;for(int i=0;i<16;i++)bits=(bits<<4)|Character.digit(frames[f].charAt(y*16+i),16);rows[f][y]=bits;} return rows; }");
            for(int atlas:atlases) {
                out.println("    private static final class Atlas"+atlas+" { static final long[][] ROWS=decode(new String[]{");
                for(int frame=0;frame<SpriteAtlas.count(atlas);frame++) {
                    String file=SpriteAtlas.file(atlas,frame);BufferedImage im=images.get(file);
                    if(im==null){im=ImageIO.read(new File("assets/sprites/"+file));images.put(file,im);}
                    int l=Math.round(im.getWidth()*SpriteAtlas.sourceLeft(atlas,frame)),t=Math.round(im.getHeight()*SpriteAtlas.sourceTop(atlas,frame));
                    int w=Math.round(im.getWidth()*SpriteAtlas.sourceRight(atlas,frame))-l,h=Math.round(im.getHeight()*SpriteAtlas.sourceBottom(atlas,frame))-t;
                    StringBuilder encoded=new StringBuilder();
                    for(int y=0;y<64;y++) {
                        long bits=0;
                        for(int x=0;x<64;x++) {
                            boolean solid=true;
                            // Only retain cells whose entire source area is opaque. Transparent
                            // padding, cast shadows and soft edges cannot trigger a false fade.
                            for(int yy=y*h/64;yy<(int)Math.ceil((y+1)*h/64.0) && solid;yy++)
                                for(int xx=x*w/64;xx<(int)Math.ceil((x+1)*w/64.0);xx++)
                                    if((im.getRGB(l+xx,t+yy)>>>24)<160){solid=false;break;}
                            if(solid)bits|=1L<<x;
                        }
                        encoded.append(String.format(Locale.ROOT,"%016x",bits));
                    }
                    out.println("        \""+encoded+"\",");
                }
                out.println("    }); }");
            }
            out.println("}");
        }
        if(check) {
            byte[] actual=java.nio.file.Files.readAllBytes(output.toPath());output.delete();
            byte[] expected=java.nio.file.Files.readAllBytes(new File("core/com/bargeboss/game/OcclusionMasks.java").toPath());
            if(!Arrays.equals(actual,expected))throw new AssertionError("Occlusion masks are stale: regenerate from production sprites");
            System.out.println("All 187 silhouette masks match production PNG interiors and atlas crops");
        }
    }
}
