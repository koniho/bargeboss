import java.awt.*;import java.awt.image.*;import java.io.*;import javax.imageio.*;
/** Offline registration: preserve image aspect, fit painted shore to 360px in a 384x256 frame.
 * A conservative radial opaque contour drives shared solid-shore cutouts. */
public final class PackIslandGround {
 public static void main(String[] args)throws Exception{
  BufferedImage src=ImageIO.read(new File("docs/art-studies/islands/ground-v1/source.png"));
  File out=new File("assets/sprites/frames/islands-ground-v1");out.mkdirs();
  StringBuilder code=new StringBuilder("package com.bargeboss.game;\n\n/** Generated by tools/PackIslandGround.java; normalized opaque ground contours. */\nfinal class IslandGroundContours {\n    static final float[][] POINTS={\n");
  for(int f=0;f<4;f++){
   int cw=src.getWidth()/2,ch=src.getHeight()/2,ox=f%2*cw,oy=f/2*ch,l=cw,t=ch,r=0,b=0;
   for(int y=0;y<ch;y++)for(int x=0;x<cw;x++)if((src.getRGB(x+ox,y+oy)>>>24)>128){l=Math.min(l,x);r=Math.max(r,x);t=Math.min(t,y);b=Math.max(b,y);}
   double scale=360.0/(r-l+1);int dh=(int)Math.round((b-t+1)*scale),dy=(256-dh)/2;
   BufferedImage cell=new BufferedImage(384,256,BufferedImage.TYPE_INT_ARGB);Graphics2D g=cell.createGraphics();g.setComposite(AlphaComposite.Src);g.setRenderingHint(RenderingHints.KEY_INTERPOLATION,RenderingHints.VALUE_INTERPOLATION_BICUBIC);
   g.drawImage(src,12,dy,372,dy+dh,ox+l,oy+t,ox+r+1,oy+b+1,null);g.dispose();ImageIO.write(cell,"png",new File(out,f+".png"));
   code.append("        {");
   for(int k=0;k<64;k++){
    double a=k*Math.PI/32,dx=Math.cos(a),yy=Math.sin(a),radius=0;
    for(double v=0;v<220;v+=.5){int x=(int)Math.round(192+dx*v),y=(int)Math.round(128+yy*v);if(x<0||y<0||x>=384||y>=256||(cell.getRGB(x,y)>>>24)<220)break;radius=v;}
    radius=Math.max(0,radius-1);if(k>0)code.append(',');code.append(String.format(java.util.Locale.ROOT,"%.6ff,%.6ff",(192+dx*radius)/384,(128+yy*radius)/256));
   }
   code.append(f==3?"}\n":"},\n");
  }
  code.append("    };\n    private IslandGroundContours(){}\n}\n");
  try(java.io.FileWriter w=new java.io.FileWriter("core/com/bargeboss/game/IslandGroundContours.java")){w.write(code.toString());}
 }
}
