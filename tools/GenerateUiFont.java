import java.awt.Font;
import java.awt.font.FontRenderContext;
import java.awt.font.GlyphVector;
import java.awt.geom.PathIterator;
import java.io.*;
import java.util.*;

/** Offline font outline exporter. Slab trapezoids preserve counters without host font APIs. */
public final class GenerateUiFont {
    public static void main(String[] args)throws Exception {
        Font font=Font.createFont(Font.TRUETYPE_FONT,new File(args[0])).deriveFont(1000f);
        FontRenderContext frc=new FontRenderContext(null,true,true);
        double cap=font.createGlyphVector(frc,"H").getVisualBounds().getHeight();
        String className=args.length>2?args[2]:"TechnicalGlyphs";
        String label=args.length>3?args[3]:"Rajdhani SemiBold (SIL OFL)";
        double shear=args.length>4?Double.parseDouble(args[4]):0,stretch=args.length>5?Double.parseDouble(args[5]):1;
        String chars="ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-+:/.,!?%()'";
        if(args.length>6 && Boolean.parseBoolean(args[6]))chars+="abcdefghijklmnopqrstuvwxyz";
        PrintWriter out=new PrintWriter(args[1],"UTF-8");
        out.println("package com.bargeboss.game;\n\n// Generated by tools/GenerateUiFont.java from "+label+".\nfinal class "+className+" {");
        out.println("    static final String CHARS=\""+chars+"\";");
        StringBuilder advances=new StringBuilder("    static final float[] ADVANCES={");
        out.println("    static final float[][] FACES={");
        for(char ch:chars.toCharArray()) {
            GlyphVector glyph=font.createGlyphVector(frc,new char[]{ch});
            advances.append(String.format(Locale.ROOT,"%.6ff,",Math.max(glyph.getGlyphMetrics(0).getAdvance()/cap*stretch,(glyph.getVisualBounds().getMaxX()/cap+shear)*stretch)+.055));
            PathIterator it=glyph.getOutline().getPathIterator(null,.45);
            ArrayList<double[]> edges=new ArrayList<double[]>();TreeSet<Double> ys=new TreeSet<Double>();
            double[] v=new double[6];double x=0,y=0,sx=0,sy=0;
            while(!it.isDone()) {
                int type=it.currentSegment(v);
                if(type==PathIterator.SEG_MOVETO){x=sx=v[0];y=sy=v[1];}
                else {double nx=type==PathIterator.SEG_CLOSE?sx:v[0],ny=type==PathIterator.SEG_CLOSE?sy:v[1];
                    if(y!=ny){edges.add(new double[]{x,y,nx,ny});ys.add(y);ys.add(ny);}x=nx;y=ny;}
                it.next();
            }
            ArrayList<Double> levels=new ArrayList<Double>(ys);StringBuilder data=new StringBuilder();
            for(int i=0;i+1<levels.size();i++) {
                double top=levels.get(i),bottom=levels.get(i+1),mid=(top+bottom)/2;
                ArrayList<double[]> active=new ArrayList<double[]>();
                for(double[] edge:edges)if(mid>Math.min(edge[1],edge[3])&&mid<Math.max(edge[1],edge[3]))active.add(edge);
                Collections.sort(active,(a,b)->Double.compare(at(a,mid),at(b,mid)));
                for(int j=0;j+1<active.size();j+=2) {
                    double[] l=active.get(j),r=active.get(j+1);
                    double[] face={(at(l,top)/cap-shear*top/cap)*stretch,1+top/cap,(at(r,top)/cap-shear*top/cap)*stretch,1+top/cap,(at(r,bottom)/cap-shear*bottom/cap)*stretch,1+bottom/cap,(at(l,bottom)/cap-shear*bottom/cap)*stretch,1+bottom/cap};
                    for(double n:face){if(data.length()>0)data.append(',');data.append(Math.round(n*10000));}
                }
            }
            out.println("        decode(\""+data+"\"), // "+ch);
        }
        out.println("    };\n"+advances+"};");
        out.println("    static float[] decode(String data){String[] words=data.split(\",\");float[] result=new float[words.length];for(int i=0;i<words.length;i++)result[i]=Integer.parseInt(words[i])/10000f;return result;}\n}");
        out.close();
    }
    static double at(double[] e,double y){return e[0]+(e[2]-e[0])*(y-e[1])/(e[3]-e[1]);}
}
